"use strict";
/* Regression guard: official vendor logos, honest attribution and trusted download links. */
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const crypto=require("node:crypto");
const root=path.resolve(__dirname,"..");
const read=x=>fs.readFileSync(path.join(root,x),"utf8");
const catalog=JSON.parse(read("assets/tools.json"));
const provenance=JSON.parse(read("assets/tools/vendor/SOURCES.json"));
const ids=["everything","ventoy","rufus","irfanview","fileconverter","vlc","fdm","powertoys"];
assert.deepEqual(catalog.items.map(x=>x.id),ids);
assert.deepEqual(Object.keys(provenance.assets),ids);
const sources=provenance.assets;
const trusted=new Set(["www.voidtools.com","raw.githubusercontent.com","rufus.ie","www.irfanview.com","file-converter.io","images.videolan.org","www.freedownloadmanager.org"]);
let bytes=0;
for(const item of catalog.items){
 const record=sources[item.id];
 assert.ok(record,"Unattributed logo "+item.id);
 const vendorUrl=new URL(record.publisher_art_url);
 assert.equal(vendorUrl.protocol,"https:");
 assert.ok(trusted.has(vendorUrl.hostname),"Unexpected logo origin "+vendorUrl.hostname);
 const localFile=path.join(root,"assets/tools/vendor",item.id+".png");
 const png=fs.readFileSync(localFile);
 assert.deepEqual([...png.subarray(0,8)],[137,80,78,71,13,10,26,10]);
 assert.equal(crypto.createHash("sha256").update(png).digest("hex"),record.sha256,"Logo source integrity "+item.id);
 assert.ok(png.length<=450000);
 const preview=read(item.image);
 assert.match(preview,/<svg[^>]+viewBox="0 0 960 540"/);
 assert.match(preview,/OFFICIAL APP ICON/);
 assert.match(preview,/Original publisher logo/);
 const match=preview.match(/<image[^>]+href="data:image\/png;base64,([A-Za-z0-9+/=]+)"/);
 assert.ok(match,"Embedded source pixels missing "+item.id);
 const decoded=Buffer.from(match[1],"base64");
 assert.ok(decoded.equals(png),"Logo pixels differ from verified vendor source: "+item.id);
 assert.ok(!/<(?:script|foreignObject|iframe)\b/i.test(preview));
 assert.ok(!/<image[^>]+href="https?:/i.test(preview));
 assert.equal(item.image,"assets/tools/"+item.id+".svg");
 assert.ok(item.url.startsWith("https://"),"Legacy download destination lost");
 bytes+=png.length;
}
assert.equal(catalog.items.length,8);
const homepage=read("index.html");
const editorial=read("assets/editorial.js");
assert.ok(homepage.includes("نعرض أيقونات البرامج الأصلية"));
assert.ok(editorial.includes('img.alt="أيقونة برنامج "+tool.name+" الأصلية"'));
assert.ok(editorial.includes("tool.url"));
const ar=read("free-windows-tools/index.html");
const en=read("en/free-windows-tools/index.html");
assert.equal((ar.match(/class="directory-card tool-card"/g)||[]).length,8);
assert.equal((en.match(/class="en-product-card"/g)||[]).length,8);
assert.equal((ar.match(/الأيقونة الأصلية لبرنامج/g)||[]).length,8);
assert.equal((en.match(/Official app icon:/g)||[]).length,8);
assert.ok(ar.includes('class="directory-grid vendor-tool-grid"'));
assert.ok(en.includes('class="en-grid vendor-tool-grid"'));
assert.ok(ar.includes("الأيقونات الأصلية تُعرض للتعريف فقط"));
assert.ok(en.includes("logo rights belong to their publishers"));
const stylesheet=read("assets/editorial.css");
assert.ok(stylesheet.includes("Authentic vendor logos"));
assert.ok(stylesheet.includes(".windows-tool-picture{width:100%;aspect-ratio:16/9}"));
assert.ok(stylesheet.includes(".windows-tool-button{min-height:44px}"));
const workflow=read(".github/workflows/update-tech-news.yml");
assert.ok(workflow.includes("python scripts/build_real_tool_art.py"));
assert.ok(workflow.includes("node tests/vendor-icons-test.cjs"));
assert.ok(workflow.indexOf("python scripts/build_real_tool_art.py")<workflow.indexOf("python scripts/build_seo.py"));
const oldGen=read("scripts/generate_tool_art.py");
assert.ok(oldGen.includes("from build_real_tool_art import main"));
console.log("OFFICIAL_VENDOR_ICON_QA_PASS",JSON.stringify({programs:ids.length,assets:ids.length,embeds:ids.length,sourcePngBytes:bytes,localized:true,offline:true,linksPreserved:true}));
